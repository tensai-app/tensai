package io.github.hokanosekai.tensai.ui.screens

import io.github.hokanosekai.tensai.data.chat.ChatRepository
import io.github.hokanosekai.tensai.data.models.ModelEntity
import io.github.hokanosekai.tensai.runtime.QueueState
import io.github.hokanosekai.tensai.runtime.RuntimeGraph
import io.github.hokanosekai.tensai.runtime.residentModel
import java.io.File
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.combine
import kotlinx.coroutines.launch

/**
 * Drives Home (TEN-37): the input pill's state, and the one action the screen owns — turning
 * typed text into a conversation to navigate into.
 *
 * Unlike [io.github.hokanosekai.tensai.ui.screens.chat.ChatViewModel] this runs on a
 * **Compose-scoped** [scope] (`rememberCoroutineScope()`), not [RuntimeGraph.applicationScope].
 * Two reasons: the work is a single row insert rather than a multi-minute decode that must survive
 * leaving the screen, and [start]'s continuation navigates — which has to happen on the main
 * thread, where a `rememberCoroutineScope` lands and `applicationScope`
 * ([kotlinx.coroutines.Dispatchers.Default]) does not. A user who leaves Home before the insert
 * lands is a user who should not be navigated into a chat.
 *
 * Takes flows rather than the repositories behind them so a test can hand it a fixed queue state
 * and model list without standing up an engine — see `HomeViewModelTest`.
 */
class HomeViewModel(
    private val scope: CoroutineScope,
    private val chatRepository: ChatRepository = RuntimeGraph.chatRepository,
    queueState: Flow<QueueState> = RuntimeGraph.inferenceQueue.state,
    models: Flow<List<ModelEntity>> = RuntimeGraph.modelRepository.models,
    fileExists: (String) -> Boolean = { File(it).exists() },
) {

    /** What the pill should render — see [HomePill.state] for the rule. */
    val pillState: Flow<HomePillState> = combine(queueState, models) { state, list ->
        HomePill.state(loadedModelName = state.residentModel?.name, models = list, fileExists = fileExists)
    }

    /**
     * The in-flight [start], if any. A second tap while one is running is a no-op rather than a
     * second conversation — same belt-and-braces as `ChatViewModel.send`'s own job guard.
     */
    private var startJob: Job? = null

    /**
     * Creates the conversation [text] will be sent in and hands its id, with the trimmed text,
     * to [onStarted] — which is where `HomeScreen` navigates. Nothing is appended to the
     * conversation here: the first turn is generated by `ChatScreen` once it is on screen, so the
     * reply streams into a chat the user is actually looking at (see `TensaiDestination.Chat`'s
     * `prompt` argument).
     *
     * A no-op on blank [text], or while a previous call is still running.
     */
    fun start(text: String, onStarted: (conversationId: String, prompt: String) -> Unit) {
        val trimmed = text.trim()
        if (trimmed.isEmpty() || startJob?.isActive == true) return
        startJob = scope.launch {
            val conversationId = chatRepository.createConversation(modelId = null)
            onStarted(conversationId, trimmed)
        }
    }
}
