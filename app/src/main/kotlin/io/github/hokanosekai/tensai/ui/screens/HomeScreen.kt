/** Opacity of the 天 watermark, per the design's "barely there" background mark. */
private const val WatermarkAlpha = 0.08f

/** Side of the watermark glyph. Larger than the screen's margins on purpose — it is meant to bleed. */
private val WatermarkSize = 300.dp

/** How far past the right edge the watermark sits, so only part of the glyph is on screen. */
private val WatermarkOffsetX = 84.dp

@StringRes
private fun Greeting.labelRes(): Int = when (this) {
    Greeting.Morning -> R.string.home_greeting_morning
    Greeting.Afternoon -> R.string.home_greeting_afternoon
    Greeting.Evening -> R.string.home_greeting_evening
    Greeting.Night -> R.string.home_greeting_night
}

/**
 * Home — the app's calm shopfront (TEN-37): a greeting, the 天 watermark, four suggestions, and
 * the input pill.
 *
 * The pill is the only part with real behaviour, and it has three faces — see [HomePill.state] for
 * the rule that picks between them. Sending from the loaded face hands the typed text to
 * [onNavigateToChat], which opens a new chat carrying it (TEN-106: that chat's first send creates
 * the conversation); the reply itself is generated by
 * `ChatScreen`, so the user watches it stream rather than arriving at a chat that is already
 * halfway through one.
 *
 * @param onNavigateToChat `(prompt)`: the prompt rides along the route, see
 *   [io.github.hokanosekai.tensai.ui.navigation.TensaiDestination.Chat.ARG_PROMPT].
 * @param onNavigateToLoad routes [HomePillState.LoadNeeded]'s tap at the named model's load.
 */
@Composable
fun HomeScreen(
    onNavigateToChat: (prompt: String) -> Unit,
    onNavigateToModels: () -> Unit,
    onNavigateToLoad: (modelId: String) -> Unit,
    modifier: Modifier = Modifier,
) {
    val viewModel = remember { HomeViewModel() }

    // Null until the first combine of queue state and the model list — the pill slot stays empty
    // for that frame rather than flashing a "no model" call to action at someone who has one.
    val pillState by viewModel.pillState.collectAsState(initial = null)
    var input by rememberSaveable { mutableStateOf("") }
    val keyboardController = LocalSoftwareKeyboardController.current

    // Read on every composition rather than remembered: Home recomposes whenever the pill state or
    // the input changes, which is often enough that the greeting cannot go stale in practice. It is
    // not a ticking clock — a Home screen left untouched across 18:00 keeps saying "Good afternoon"
    // until something else recomposes it, and that is fine.
    val greeting = greetingFor(LocalTime.now().hour)

    Box(modifier = modifier.fillMaxSize()) {
        KanjiGlyph(
            size = WatermarkSize,
            // Off to the right and bleeding past the edge. KanjiGlyph draws into a Canvas with
            // cleared semantics and takes no click, so this stays background texture: it is not
            // reachable by touch or by the accessibility cursor.
            modifier = Modifier
                .align(Alignment.CenterEnd)
                .offset(x = WatermarkOffsetX)
                .alpha(WatermarkAlpha),
        )

        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(24.dp),
            verticalArrangement = Arrangement.SpaceBetween,
        ) {
            Column {
                Text(
                    text = stringResource(greeting.labelRes()),
                    style = MaterialTheme.typography.headlineLarge,
                    color = MaterialTheme.colorScheme.onBackground,
                )
                Spacer(Modifier.height(8.dp))
                Text(
                    text = stringResource(R.string.home_subtitle),
                    style = MaterialTheme.typography.bodyLarge,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }

            when (val state = pillState) {
                null -> Unit

                is HomePillState.Ready -> Column {
                    // Chips only exist alongside a working pill: they fill it, and there is nothing
                    // to fill in the other two states.
                    SuggestionChips(onPick = { input = it }, modifier = Modifier.fillMaxWidth())
                    Spacer(Modifier.height(12.dp))
                    InputPill(
                        value = input,
                        onValueChange = { input = it },
                        onSend = {
                            viewModel.start(input) { prompt ->
                                input = ""
                                keyboardController?.hide()
                                onNavigateToChat(prompt)
                            }
                        },
                        // Home never generates: a reply always streams on the chat screen. A
                        // generation running in a *different* conversation is deliberately not
                        // surfaced here — a stop button on Home would cancel work the user cannot
                        // see, which is worse than not offering it.
                        onStop = {},
                        isGenerating = false,
                    )
                }

                is HomePillState.LoadNeeded -> CalloutPill(
                    text = stringResource(R.string.home_pill_load_model, state.displayName),
                    showDot = true,
                    onClick = { onNavigateToLoad(state.modelId) },
                )

                HomePillState.NoModel -> CalloutPill(
                    text = stringResource(R.string.home_pill_no_model),
                    showDot = false,
                    onClick = onNavigateToModels,
                )
            }
        }
    }
}

/**
 * The pill's non-typing faces: same silhouette as [InputPill], but the whole thing is one tap that
 * goes and gets the app into a state where typing means something.
 *
 * @param showDot the lavender dot that marks "there is a model here, it just is not loaded" — the
 *   [HomePillState.LoadNeeded] face. [HomePillState.NoModel] has nothing to point at, so it gets no
 *   dot.
 */
@Composable
private fun CalloutPill(text: String, showDot: Boolean, onClick: () -> Unit, modifier: Modifier = Modifier) {
    Surface(
        onClick = onClick,
        shape = TensaiShapes.extraLarge,
        color = MaterialTheme.colorScheme.surfaceVariant,
        modifier = modifier.fillMaxWidth(),
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(12.dp),
            modifier = Modifier.padding(horizontal = 20.dp, vertical = 18.dp),
        ) {
            if (showDot) {
                Box(
                    modifier = Modifier
                        .size(8.dp)
                        .clip(CircleShape)
                        .background(MaterialTheme.colorScheme.primary),
                )
            }
            Text(
                text = text,
                style = MaterialTheme.typography.bodyLarge,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                maxLines = 1,
            )
        }
    }
}
